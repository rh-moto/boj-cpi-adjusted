def build_monthly_subsidy():
    """月次の推定補助額を算出して保存"""
    records = []
    for ym, cf_price, retail_price in GRAPH_DATA:
        subsidy = cf_price - retail_price
        records.append({
            "year_month": ym,
            "counterfactual_price": cf_price,
            "retail_price": retail_price,
            "subsidy_total": subsidy,
        })

    df = pd.DataFrame(records)
    print("=== ガソリン月次補助額（PDFグラフ読み取り）===")
    print(df.to_string(index=False))
    print(f"\n補助額の範囲: {df['subsidy_total'].min():.0f}〜{df['subsidy_total'].max():.0f}円/L")

    outpath = POLICY_DIR / "gasoline_subsidy_monthly.csv"
    df.to_csv(outpath, index=False)
    print(f"\n保存: {outpath}")
    return df


if __name__ == "__main__":
    build_monthly_subsidy()
